-- เลื่อนบัญชีที่สมัครสมาชิกไว้แล้วให้เป็น "แอดมิน"
--
-- วิธีใช้:
--   1) สมัครสมาชิกปกติในเว็บแอปด้วยอีเมลที่ต้องการให้เป็นแอดมินก่อน 1 ครั้ง
--   2) แก้อีเมลด้านล่างให้ตรงกับบัญชีนั้น
--   3) วางรันใน Supabase SQL Editor
--
-- รันซ้ำได้ปลอดภัย ไม่กระทบบัญชีอื่น
-- =========================================================

update public.profiles
set role = 'admin'
where email = 'your-email@example.com';   -- 🔧 แก้อีเมลตรงนี้

-- ตรวจสอบผลลัพธ์
select id, email, name, role from public.profiles where role = 'admin';
